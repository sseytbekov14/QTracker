package com.kpmg.qtracker.migration;

import org.flywaydb.core.Flyway;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * V22 drops users.role and users.secondary_role and keeps the values that were set in users_role_backup; the
 * hand-run undo script brings the columns back with exactly those values.
 */
class V22UserRoleColumnsMigrationTest {

    private static final String UNDO_SCRIPT = "/db/rollback/V22__undo_drop_user_role_columns.sql";

    private String url;
    private Connection connection;

    @BeforeEach
    void setUp() throws Exception {
        url = "jdbc:h2:mem:v22-" + UUID.randomUUID() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1";
        connection = DriverManager.getConnection(url, "sa", "");
        // users as V21 leaves it (not empty, so Flyway takes it as the baseline)
        execute("CREATE TABLE users (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                + " mail VARCHAR(255) NOT NULL UNIQUE, displayname VARCHAR(255), role VARCHAR(255),"
                + " secondary_role VARCHAR(255), enabled BOOLEAN NOT NULL DEFAULT TRUE,"
                + " admin_access BOOLEAN NOT NULL DEFAULT FALSE, password VARCHAR(255),"
                + " access_level VARCHAR(20) NOT NULL, access_scope VARCHAR(20) NOT NULL)");
        // As on prod: one SoQM with the old role, the other SoQM and everyone else without one
        execute("INSERT INTO users (mail, role, secondary_role, admin_access, access_level, access_scope) VALUES "
                + "('soqm-old@x.kz', 'SOQM_TEAM', NULL, TRUE, 'SOQM', 'ALL'), "
                + "('soqm@x.kz', NULL, NULL, TRUE, 'SOQM', 'ALL'), "
                + "('user@x.kz', NULL, NULL, FALSE, 'PARTICIPANT', 'OWN'), "
                + "('kdn@x.kz', NULL, NULL, FALSE, 'READ_ONLY', 'KDN'), "
                // Not on prod: a second role alone, and both
                + "('second@x.kz', NULL, 'PROCESS_OWNER', FALSE, 'PARTICIPANT', 'OWN'), "
                + "('both@x.kz', 'FACILITATOR', 'KDN', FALSE, 'READ_ONLY', 'KDN')");
    }

    @AfterEach
    void tearDown() throws Exception {
        try (Statement st = connection.createStatement()) {
            st.execute("SHUTDOWN");
        }
        connection.close();
    }

    @Test
    void theColumnsGo_theValuesThatWereSetAreKept_andNothingElseChanges() throws Exception {
        Map<String, String> accessBefore = access();

        flyway().migrate();

        assertThat(roleColumns()).isZero();
        assertThat(rows("SELECT u.mail, COALESCE(b.role, '-') || '|' || COALESCE(b.secondary_role, '-') "
                + "FROM users_role_backup b JOIN users u ON u.id = b.user_id ORDER BY u.mail"))
                .containsExactly(
                        Map.entry("both@x.kz", "FACILITATOR|KDN"),
                        Map.entry("second@x.kz", "-|PROCESS_OWNER"),
                        Map.entry("soqm-old@x.kz", "SOQM_TEAM|-"));
        assertThat(access()).isEqualTo(accessBefore);
    }

    @Test
    void theUndoScript_bringsTheColumnsBackWithTheirValues() throws Exception {
        Map<String, String> before = roles();
        flyway().migrate();
        // Created after V22: no role to restore
        execute("INSERT INTO users (mail, admin_access, access_level, access_scope) "
                + "VALUES ('new@x.kz', FALSE, 'READ_ONLY', 'OWN')");

        runUndoScript();

        Map<String, String> undone = roles();
        assertThat(undone).containsAllEntriesOf(before).containsEntry("new@x.kz", "-|-").hasSize(before.size() + 1);
        assertThat(rows("SELECT LOWER(column_name), is_nullable || '|' || data_type || '|' || character_maximum_length "
                + "FROM information_schema.columns WHERE LOWER(table_name) = 'users' "
                + "AND LOWER(column_name) IN ('role', 'secondary_role') ORDER BY 1"))
                .containsExactly(
                        Map.entry("role", "YES|CHARACTER VARYING|255"),
                        Map.entry("secondary_role", "YES|CHARACTER VARYING|255"));
        assertThat(single("SELECT COUNT(*) FROM information_schema.tables WHERE LOWER(table_name) = 'users_role_backup'"))
                .isEqualTo("0");
    }

    private Map<String, String> roles() throws Exception {
        return rows("SELECT mail, COALESCE(role, '-') || '|' || COALESCE(secondary_role, '-') FROM users ORDER BY mail");
    }

    private Map<String, String> access() throws Exception {
        return rows("SELECT mail, access_level || '/' || access_scope || '/' || admin_access FROM users ORDER BY mail");
    }

    private int roleColumns() throws Exception {
        return Integer.parseInt(single("SELECT COUNT(*) FROM information_schema.columns WHERE LOWER(table_name) = 'users'"
                + " AND LOWER(column_name) IN ('role', 'secondary_role')"));
    }

    private void runUndoScript() throws Exception {
        String script;
        try (InputStream in = getClass().getResourceAsStream(UNDO_SCRIPT)) {
            assertThat(in).as(UNDO_SCRIPT).isNotNull();
            script = new String(in.readAllBytes(), StandardCharsets.UTF_8);
        }
        StringBuilder withoutComments = new StringBuilder();
        for (String line : script.split("\n")) {
            if (!line.trim().startsWith("--")) {
                withoutComments.append(line).append('\n');
            }
        }
        for (String sql : withoutComments.toString().split(";")) {
            if (!sql.isBlank()) {
                execute(sql);
            }
        }
    }

    private void execute(String sql) throws SQLException {
        try (Statement st = connection.createStatement()) {
            st.execute(sql);
        }
    }

    private String single(String sql) throws Exception {
        try (Statement st = connection.createStatement(); ResultSet rs = st.executeQuery(sql)) {
            assertThat(rs.next()).as(sql).isTrue();
            return rs.getString(1);
        }
    }

    private Map<String, String> rows(String sql) throws Exception {
        Map<String, String> out = new LinkedHashMap<>();
        try (Statement st = connection.createStatement(); ResultSet rs = st.executeQuery(sql)) {
            while (rs.next()) {
                out.put(rs.getString(1), rs.getString(2));
            }
        }
        return out;
    }

    private Flyway flyway() {
        return Flyway.configure()
                .dataSource(url, "sa", "")
                .locations("classpath:db/migration")
                .baselineOnMigrate(true)
                .baselineVersion("21")
                .target("22")
                .load();
    }
}
