package com.kpmg.qtracker.migration;

import db.migration.V30__Documents_attachments_into_details;
import org.flywaydb.core.Flyway;
import org.flywaydb.core.api.migration.Context;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.Statement;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

/**
 * V30 copies the files of the Documents tab into Details: the list on the control and the upload records, author,
 * stage and time kept, nothing removed; run again it adds nothing; on an empty database it does nothing.
 */
class V30DocumentsIntoDetailsMigrationTest {

    private String url;
    private Connection connection;

    @BeforeEach
    void setUp() throws Exception {
        url = "jdbc:h2:mem:v30-" + UUID.randomUUID() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1";
        connection = DriverManager.getConnection(url, "sa", "");
        execute("CREATE TABLE controls (id BIGINT PRIMARY KEY, control_id VARCHAR(255),"
                + " attachment_details_path TEXT, attachment_documents_path TEXT)");
        execute("CREATE TABLE control_attachments (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                + " control_id BIGINT NOT NULL REFERENCES controls(id) ON DELETE CASCADE, tab VARCHAR(20) NOT NULL,"
                + " file_name VARCHAR(1000) NOT NULL, uploaded_by_email VARCHAR(255), uploaded_stage VARCHAR(50),"
                + " uploaded_at TIMESTAMP, CONSTRAINT uq_control_attachments_file UNIQUE (control_id, tab, file_name))");
    }

    @AfterEach
    void tearDown() throws Exception {
        execute("SHUTDOWN");
        connection.close();
    }

    @Test
    void theDocumentsFiles_areInDetails_withTheirAuthor_nothingRemoved_andAgainNothingAdded() throws Exception {
        // 1: Details and Documents, one name in both; 2: only Documents (Cyrillic, spaces, a separator too many);
        // 3: only Details; 4: none
        execute("INSERT INTO controls VALUES (1, 'HR-1', 'a.pdf;same.xlsx', 'doc.docx;same.xlsx')");
        execute("INSERT INTO controls VALUES (2, 'HR-2', NULL, ' Политика.docx ; ;scan (1).png;')");
        execute("INSERT INTO controls VALUES (3, 'HR-3', 'only.pdf', NULL)");
        execute("INSERT INTO controls VALUES (4, 'HR-4', NULL, '')");
        record(1, "DETAILS", "a.pdf", "fac@kpmg.kz", "IN_PROGRESS", "2026-10-01 10:00:00");
        record(1, "DETAILS", "same.xlsx", "fac@kpmg.kz", "IN_PROGRESS", "2026-10-01 10:01:00");
        record(1, "DOCUMENTS", "doc.docx", "op@kpmg.kz", "REVIEW", "2026-10-02 11:00:00");
        record(1, "DOCUMENTS", "same.xlsx", "op@kpmg.kz", "REVIEW", "2026-10-02 11:01:00");
        record(2, "DOCUMENTS", "Политика.docx", "po@kpmg.kz", "PROCESS_OWNER_REVIEW", "2026-10-03 12:00:00");
        record(2, "DOCUMENTS", "scan (1).png", null, null, null);
        int documentsBefore = count("SELECT COUNT(*) FROM control_attachments WHERE tab = 'DOCUMENTS'");

        flyway().migrate();

        assertThat(details(1)).isEqualTo("a.pdf;same.xlsx;doc.docx");
        assertThat(details(2)).isEqualTo("Политика.docx;scan (1).png");
        assertThat(details(3)).isEqualTo("only.pdf");
        assertThat(details(4)).isNull();
        // The old tab is kept as it was
        assertThat(single("SELECT attachment_documents_path FROM controls WHERE id = 1")).isEqualTo("doc.docx;same.xlsx");
        assertThat(count("SELECT COUNT(*) FROM control_attachments WHERE tab = 'DOCUMENTS'")).isEqualTo(documentsBefore);
        // One DETAILS record per Documents file, author / stage / time as uploaded; same.xlsx keeps its Details record
        assertThat(single("SELECT uploaded_by_email || '|' || uploaded_stage || '|' || uploaded_at FROM control_attachments"
                + " WHERE control_id = 1 AND tab = 'DETAILS' AND file_name = 'doc.docx'"))
                .startsWith("op@kpmg.kz|REVIEW|2026-10-02 11:00");
        assertThat(single("SELECT uploaded_by_email FROM control_attachments WHERE control_id = 1 AND tab = 'DETAILS'"
                + " AND file_name = 'same.xlsx'")).isEqualTo("fac@kpmg.kz");
        assertThat(single("SELECT uploaded_by_email FROM control_attachments WHERE control_id = 2 AND tab = 'DETAILS'"
                + " AND file_name = 'Политика.docx'")).isEqualTo("po@kpmg.kz");
        assertThat(count("SELECT COUNT(*) FROM control_attachments WHERE control_id = 2 AND tab = 'DETAILS'"
                + " AND file_name = 'scan (1).png' AND uploaded_by_email IS NULL")).isEqualTo(1);
        // Every Documents file now has a Details record and is on the Details list
        assertThat(count("SELECT COUNT(*) FROM control_attachments d WHERE d.tab = 'DOCUMENTS' AND NOT EXISTS"
                + " (SELECT 1 FROM control_attachments x WHERE x.control_id = d.control_id AND x.tab = 'DETAILS'"
                + " AND x.file_name = d.file_name)")).isZero();
        int detailsAfter = count("SELECT COUNT(*) FROM control_attachments WHERE tab = 'DETAILS'");
        assertThat(detailsAfter).isEqualTo(2 + 3);

        // Run again: nothing more
        Context context = mock(Context.class);
        when(context.getConnection()).thenReturn(connection);
        new V30__Documents_attachments_into_details().migrate(context);
        assertThat(details(1)).isEqualTo("a.pdf;same.xlsx;doc.docx");
        assertThat(details(2)).isEqualTo("Политика.docx;scan (1).png");
        assertThat(count("SELECT COUNT(*) FROM control_attachments WHERE tab = 'DETAILS'")).isEqualTo(detailsAfter);
    }

    @Test
    void anEmptyDatabase_isFine() throws Exception {
        flyway().migrate();
        assertThat(count("SELECT COUNT(*) FROM control_attachments")).isZero();
    }

    @Test
    void merge_appendsOnlyNamesNotListed() {
        assertThat(V30__Documents_attachments_into_details.merge("a;b", "b;c")).isEqualTo("a;b;c");
        assertThat(V30__Documents_attachments_into_details.merge("a", " ")).isEqualTo("a");
        assertThat(V30__Documents_attachments_into_details.merge(null, null)).isNull();
    }

    private String details(long id) throws Exception {
        return single("SELECT attachment_details_path FROM controls WHERE id = " + id);
    }

    private void record(long control, String tab, String name, String email, String stage, String at) throws Exception {
        execute("INSERT INTO control_attachments (control_id, tab, file_name, uploaded_by_email, uploaded_stage, uploaded_at)"
                + " VALUES (" + control + ", '" + tab + "', '" + name + "', " + quote(email) + ", " + quote(stage) + ", "
                + (at == null ? "NULL" : "TIMESTAMP '" + at + "'") + ")");
    }

    private static String quote(String value) {
        return value == null ? "NULL" : "'" + value + "'";
    }

    private void execute(String sql) throws Exception {
        try (Statement st = connection.createStatement()) {
            st.execute(sql);
        }
    }

    private int count(String sql) throws Exception {
        return Integer.parseInt(single(sql));
    }

    private String single(String sql) throws Exception {
        try (Statement st = connection.createStatement(); ResultSet rs = st.executeQuery(sql)) {
            assertThat(rs.next()).as(sql).isTrue();
            return rs.getString(1);
        }
    }

    private Flyway flyway() {
        return Flyway.configure()
                .dataSource(url, "sa", "")
                .locations("classpath:db/migration")
                .baselineOnMigrate(true)
                .baselineVersion("29")
                .target("30")
                .load();
    }
}
